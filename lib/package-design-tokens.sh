 * @param {string} buildPath
 * @returns {object}
 */
export function createCssVarsPlatform(buildPath) {
	return {
		buildPath: buildPath.endsWith('/') ? buildPath : `${buildPath}/`,
		transformGroup: 'tokens-studio',
		transforms: ['name/kebab'],
