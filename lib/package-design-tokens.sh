add_design_tokens_readme() {
	log_info "Creating design-tokens README.md..."
	cd "$TARGET_FOLDER/packages/design-tokens" || exit

	cat >README.md <<'EOF'
# `@repo/design-tokens`

Design tokens for the Design System, built with [Style Dictionary](https://amzn.github.io/style-dictionary/) using the [W3C Design Token Community Group (DTCG)](https://tr.designtokens.org/format/) format.

## Token Sources

Tokens are exported from Figma using [Tokens Studio](https://tokens.studio/) and stored in `tokens/` directory.

### File Structure

```
tokens/
├── base.json         # Core palette (colors, primitives)
├── semantic.json     # Semantic tokens (references base)
├── typography.json   # Font families, sizes, weights
└── spacing.json      # Spacing scale
```

## Outputs

Style Dictionary generates multiple output formats:

| Format | File | Usage |
|--------|------|-------|
| CSS | `dist/tokens.css` | Import in stylesheets |
| ESM | `dist/index.js` | `import tokens from '@repo/design-tokens'` |
| CJS | `dist/index.cjs` | `require('@repo/design-tokens')` |
| TypeScript | `dist/index.d.ts` | Type definitions |
| Tailwind JS | `dist/tailwind.js` | Extend Tailwind v3 theme config |
| Tailwind CSS | `dist/tailwind-theme.css` | Tailwind v4 `@theme` directive |

## Usage

### CSS

```css
@import '@repo/design-tokens/css';

.button {
  background-color: var(--semantic-accent-default);
  color: var(--semantic-foreground-inverse);
}
```

### JavaScript/TypeScript

```typescript
import tokens from '@repo/design-tokens'

console.log(tokens.color.primary[500]) // '#3b82f6'
```

### Tailwind CSS v4

Import the generated `@theme` CSS in your app's stylesheet:

```css
@import "tailwindcss";
@import "@repo/design-tokens/tailwind-theme";

/* Your app styles */
```

### Tailwind CSS v3 (legacy)

```javascript
// tailwind.config.js
import designTokens from '@repo/design-tokens/tailwind'

export default {
  theme: {
    extend: designTokens,
  },
}
```

## Development

```bash
# Build tokens
pnpm build

# Watch for changes
pnpm build:watch
```

## Tokens Studio Integration

This package expects tokens from Tokens Studio in DTCG format. Configure Tokens Studio to:

1. Use **W3C DTCG** format for exports
2. Commit directly to this repository
3. Use commit message prefixes (`major`, `minor`, `fix`) for versioning

### CI/CD

The build pipeline should be triggered on commits to `tokens/` directory. The commit message prefix determines the version bump:

- `major:` - Breaking changes (e.g., renamed tokens)
- `minor:` - New tokens added
- `fix:` - Token value corrections
EOF

	log_success "design-tokens README.md created"
}
