# Functions for creating the @repo/design-tokens package with Style Dictionary

create_design_tokens_package() {
	log_info "Creating @repo/design-tokens package..."
	cd "$TARGET_FOLDER/packages" || exit

	mkdir -p design-tokens
	cd design-tokens || exit

	NPM_CONFIG_INIT_LICENSE="LGPL-3.0-or-later" \
		NPM_CONFIG_INIT_AUTHOR_NAME="${DEVELOPER}" \
		NPM_CONFIG_INIT_DESCRIPTION="Design tokens for the ${ORGANIZATION_NAME} Design System (Style Dictionary + DTCG)" \
		NPM_CONFIG_INIT_VERSION="1.0.0" \
		NPM_CONFIG_INIT_NAME="@repo/design-tokens" \
		NPM_CONFIG_INIT_TYPE="module" \
		NPM_CONFIG_INIT_PRIVATE="true" \
		pnpm init

	# Add exports and files configuration
	jq '. + {
		"exports": {
			".": {
				"types": "./dist/index.d.ts",
				"import": "./dist/index.js",
				"require": "./dist/index.cjs"
			},
			"./css": "./dist/tokens.css",
			"./tailwind": {
				"types": "./dist/tailwind.d.ts",
				"import": "./dist/tailwind.js",
				"require": "./dist/tailwind.cjs"
			},
			"./tailwind-theme": "./dist/tailwind-theme.css"
		},
		"files": ["dist"],
		"scripts": {
			"build": "style-dictionary build --config sd.config.js",
			"build:watch": "chokidar \"tokens/**/*.json\" -c \"pnpm build\"",
			"clean": "rm -rf dist",
			"typecheck": "tsc --noEmit"
		},
		"devDependencies": {
			"chokidar-cli": "catalog:",
			"style-dictionary": "catalog:",
			"typescript": "catalog:"
		}
	}' package.json >package.json.tmp && mv package.json.tmp package.json

	log_success "@repo/design-tokens package created"
}

add_design_tokens_config() {
	log_info "Adding Style Dictionary configuration..."
	cd "$TARGET_FOLDER/packages/design-tokens" || exit

	# Create Style Dictionary config for DTCG format
	cat >sd.config.js <<'EOF'
import StyleDictionary from 'style-dictionary'

// Custom transform for DTCG $value format
StyleDictionary.registerTransform({
	name: 'dtcg/value',
	type: 'value',
	transform: (token) => token.$value ?? token.value,
})

// Custom format for Tailwind CSS theme
StyleDictionary.registerFormat({
	name: 'tailwind/theme',
	format: ({ dictionary }) => {
		const buildTailwindObject = (tokens, prefix = '') => {
			const result = {}

			for (const [key, value] of Object.entries(tokens)) {
				if (value.$value !== undefined) {
					// Leaf token
					result[key] = value.$value
				} else if (typeof value === 'object' && value !== null) {
					// Nested group
					result[key] = buildTailwindObject(value, `${prefix}${key}-`)
				}
			}

			return result
		}

		const theme = buildTailwindObject(dictionary.tokens)

		return [
			'/** @type {import("tailwindcss").Config["theme"]} */',
			`const theme = ${JSON.stringify(theme, null, '\t')}`,
			'',
			'export default theme',
		].join('\n')
	},
})

// Custom format for TypeScript declarations
StyleDictionary.registerFormat({
	name: 'typescript/declarations',
	format: ({ dictionary }) => {
		const generateTypes = (tokens, indent = '') => {
			const lines = []

			for (const [key, value] of Object.entries(tokens)) {
				if (value.$value !== undefined) {
					lines.push(`${indent}readonly ${key}: string`)
				} else if (typeof value === 'object' && value !== null) {
					lines.push(`${indent}readonly ${key}: {`)
					lines.push(generateTypes(value, indent + '\t'))
					lines.push(`${indent}}`)
				}
			}

			return lines.join('\n')
		}

		return [
			'// Auto-generated by Style Dictionary',
			'// Do not edit directly',
			'',
			'export interface DesignTokens {',
			generateTypes(dictionary.tokens, '\t'),
			'}',
			'',
			'declare const tokens: DesignTokens',
			'export default tokens',
		].join('\n')
	},
})

// Custom format for Tailwind v4 @theme CSS
StyleDictionary.registerFormat({
	name: 'tailwind/theme-css',
	format: ({ dictionary }) => {
		const lines = [
			'/**',
			' * Tailwind v4 @theme CSS',
			' * Auto-generated by Style Dictionary from design tokens.',
			' * Do not edit directly.',
			' *',
			' * Usage in your app stylesheet:',
			' *   @import "@repo/design-tokens/tailwind-theme";',
			' */',
			'',
			'@theme {',
		]

		const processTokens = (tokens, prefix = '') => {
			for (const [key, value] of Object.entries(tokens)) {
				if (value.$value !== undefined) {
					// Use the CSS variable name from tokens.css
					const varName = `${prefix}${key}`.replace(/([A-Z])/g, '-$1').toLowerCase()
					lines.push(`\t--${varName}: var(--${varName});`)
				} else if (typeof value === 'object' && value !== null && !key.startsWith('$')) {
					processTokens(value, `${prefix}${key}-`)
				}
			}
		}

		processTokens(dictionary.tokens)
		lines.push('}')

		return lines.join('\n')
	},
})

export default {
	source: ['tokens/**/*.json'],
	preprocessors: ['tokens-studio'],
	platforms: {
		css: {
			transformGroup: 'css',
			transforms: ['dtcg/value', 'name/kebab'],
			buildPath: 'dist/',
			files: [
				{
					destination: 'tokens.css',
					format: 'css/variables',
					options: {
						outputReferences: true,
					},
				},
			],
		},
		js: {
			transformGroup: 'js',
			transforms: ['dtcg/value', 'name/camel'],
			buildPath: 'dist/',
			files: [
				{
					destination: 'index.js',
					format: 'javascript/es6',
				},
				{
					destination: 'index.cjs',
					format: 'javascript/module-flat',
				},
			],
		},
		ts: {
			transformGroup: 'js',
			transforms: ['dtcg/value', 'name/camel'],
			buildPath: 'dist/',
			files: [
				{
					destination: 'index.d.ts',
					format: 'typescript/declarations',
				},
			],
		},
		tailwind: {
			transformGroup: 'js',
			transforms: ['dtcg/value', 'name/camel'],
			buildPath: 'dist/',
			files: [
				{
					destination: 'tailwind.js',
					format: 'tailwind/theme',
				},
				{
					destination: 'tailwind.cjs',
					format: 'tailwind/theme',
				},
				{
					destination: 'tailwind.d.ts',
					format: 'typescript/declarations',
				},
			],
		},
		'tailwind-theme': {
			transformGroup: 'css',
			transforms: ['dtcg/value', 'name/kebab'],
			buildPath: 'dist/',
			files: [
				{
					destination: 'tailwind-theme.css',
					format: 'tailwind/theme-css',
				},
			],
		},
	},
}
EOF

	log_success "Style Dictionary configuration added"
}

